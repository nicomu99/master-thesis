from typing import Optional

from dataclasses import dataclass


@dataclass
class BatchInfo:
    """Data class holding information about batches sent to the LLM client.
    
    Attributes:
        batch_id (str): Batch identifier. The identifier is generated by the LLM client.
        status (str): Possibly outdated process status, indicating what step the batch is currently going through. 
            Can be "send", "sent", "failed", "in_progress", "completed" or "retrieved". If the status is "send", 
            a request file has already been created, but the batch has not been sent to the API. The statuses "failed",
            "in_progress" and "completed" correspond to the steps of the API. If the batch can be retrieved, the status
            is "completed", this changes to "retrieved" when the API response has been fetched.
        output_file_id (str): File path containing the response of the API.
    """
    batch_id: str
    status: str
    output_file_id: Optional[str]
