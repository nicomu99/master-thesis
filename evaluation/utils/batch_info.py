from typing import Optional
from dataclasses import dataclass
from pathlib import Path

from .enums import BatchType, BatchStatus
from .constants import TEMP_PATH
from .log_conf import logging

log = logging.getLogger(__name__)
log.setLevel(logging.DEBUG)


@dataclass
class BatchInfo:
    """Data class holding information about batches sent to the LLM client.

    Attributes:
        batch_id (str): Batch identifier. The identifier is generated by the LLM API.
        task_id (str): Identifier used to map the batch to a task.
        batch_type (BatchType): Indicates what information the batch contains. Can be "personas" or "answers".
        status (str): Possibly outdated process status, indicating what step the batch is currently going through.
            Can be "send", "sent", "failed", "in_progress", "completed", "error", or "retrieved".

            If the status is "send", a request file has already been created, but the batch has not been sent to the
            API. The statuses "failed", "in_progress" and "completed" correspond to the steps of the API.
            If the batch can be retrieved, the status is "completed", this changes to "retrieved" or "error" after the
            response has been fetched. Defaults to "sent"
        output_file_id (str): File id containing the response of the API.
        local_output_file (Path): Local file path of the response.
        error_file_id (str): File path containing possible errors that happened during processing this request.
        local_error_file (Path): Local file path of the error response.
    """

    batch_id: str
    task_id: str
    batch_type: BatchType
    status: BatchStatus = BatchStatus.SENT
    output_file_id: Optional[str] = None
    local_output_file: Optional[Path] = None
    error_file_id: Optional[str] = None
    local_error_file: Optional[Path] = None

    _STR_TRANSITIONS = {
        "failed": BatchStatus.FAILED,
        "in_progress": BatchStatus.IN_PROGRESS,
        "completed": BatchStatus.COMPLETED
    }

    def is_completed(self):
        return self.status == BatchStatus.COMPLETED

    def is_failed(self):
        return self.status == BatchStatus.FAILED

    def is_in_progress(self):
        return self.status == BatchStatus.IN_PROGRESS

    def has_finished(self):
        return self.status in (BatchStatus.RETRIEVED, BatchStatus.ERROR)

    def set_status(
        self,
        status: BatchStatus
    ):
        self.status = status

    def create_output_file(self) -> Path:
        self.local_output_file = TEMP_PATH / f"{self.task_id}_{self.batch_id}_output.jsonl"
        return self.local_output_file

    def create_error_file(self) -> Path:
        self.local_error_file = TEMP_PATH / f"{self.task_id}_{self.batch_id}_error.jsonl"
        return self.local_error_file

    def update_status(
        self,
        new_status: str
    ):
        try:
            self.status = self._STR_TRANSITIONS[new_status]
        except KeyError:
            log.warning(
                "No status transition defined for status %s. Will keep old status.",
                new_status)
